-- Single-purpose additive third-party breed DNA summary table.
-- Only after exact Django migration allowlist AND verified encrypted offsite backup.
-- No existing Dog, HealthRecord, DogDocument, payment or account rows are changed.
-- Execute exclusively as cca_shadow_admin. Runtime cca_app retains no schema DDL.
BEGIN;
SET LOCAL lock_timeout = '10s';
SET LOCAL statement_timeout = '50s';

DO $$
BEGIN
    IF current_database() <> 'cca_live' OR current_user <> 'cca_shadow_admin' THEN
        RAISE EXCEPTION 'Unexpected database or schema administrator';
    END IF;
    IF to_regclass('django_app.registry_healthrecord') IS NULL
       OR to_regclass('django_app.registry_dogdocument') IS NULL
       OR to_regclass('django_app.django_migrations') IS NULL THEN
        RAISE EXCEPTION 'Required existing tables or migration ledger are missing';
    END IF;
    IF NOT EXISTS (
        SELECT 1 FROM django_app.django_migrations
        WHERE app = 'registry' AND name = '0017_moderation_staff_deregistration'
    ) THEN
        RAISE EXCEPTION 'Required preceding registry migration not applied';
    END IF;
    IF EXISTS (
        SELECT 1 FROM django_app.django_migrations
        WHERE app = 'registry' AND name = '0018_breed_dna_report'
    ) THEN
        RAISE EXCEPTION 'Breed DNA migration was already applied';
    END IF;
    IF to_regclass('django_app.registry_breeddnareport') IS NOT NULL
       OR to_regclass('django_app.registry_breeddnareport_id_seq') IS NOT NULL THEN
        RAISE EXCEPTION 'Unexpected preexisting DNA table or identity sequence';
    END IF;
    IF has_schema_privilege('cca_app', 'django_app', 'CREATE') THEN
        RAISE EXCEPTION 'Runtime account must never hold schema CREATE privilege';
    END IF;
END $$;

CREATE TABLE django_app.registry_breeddnareport (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    provider varchar(100) NOT NULL,
    cane_corso_percentage numeric(5,2) NOT NULL,
    composition jsonb NOT NULL,
    consent_full_report boolean NOT NULL DEFAULT false,
    created_at timestamptz NOT NULL,
    evidence_document_id bigint NOT NULL UNIQUE,
    health_record_id bigint NOT NULL UNIQUE,
    CONSTRAINT cca_breed_dna_document_fk
        FOREIGN KEY (evidence_document_id)
        REFERENCES django_app.registry_dogdocument (id)
        DEFERRABLE INITIALLY DEFERRED,
    CONSTRAINT cca_breed_dna_health_fk
        FOREIGN KEY (health_record_id)
        REFERENCES django_app.registry_healthrecord (id)
        DEFERRABLE INITIALLY DEFERRED
);

-- The runtime app can read/write rows but never create/alter database objects.
GRANT SELECT, INSERT, UPDATE, DELETE ON django_app.registry_breeddnareport TO cca_app;
GRANT USAGE, SELECT ON SEQUENCE django_app.registry_breeddnareport_id_seq TO cca_app;

INSERT INTO django_app.django_migrations (app, name, applied)
VALUES ('registry', '0018_breed_dna_report', CURRENT_TIMESTAMP);

DO $$
DECLARE
    exact_columns integer;
BEGIN
    SELECT count(*) INTO exact_columns
    FROM information_schema.columns
    WHERE table_schema = 'django_app'
      AND table_name = 'registry_breeddnareport'
      AND column_name IN (
          'id', 'provider', 'cane_corso_percentage', 'composition',
          'consent_full_report', 'created_at', 'evidence_document_id', 'health_record_id'
      );
    IF exact_columns <> 8 THEN
        RAISE EXCEPTION 'DNA report table does not contain all eight fields';
    END IF;
    IF (
        SELECT count(*) FROM django_app.django_migrations
        WHERE app = 'registry' AND name = '0018_breed_dna_report'
    ) <> 1 THEN
        RAISE EXCEPTION 'DNA migration history was not recorded exactly once';
    END IF;
    IF NOT has_table_privilege('cca_app', 'django_app.registry_breeddnareport', 'SELECT,INSERT,UPDATE,DELETE') THEN
        RAISE EXCEPTION 'Runtime data-table permissions missing';
    END IF;
    IF has_schema_privilege('cca_app', 'django_app', 'CREATE') THEN
        RAISE EXCEPTION 'Runtime role acquired forbidden schema permission';
    END IF;
END $$;
COMMIT;
